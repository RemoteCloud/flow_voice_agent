const EN = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen", "sixteen", "seventeen", "eighteen", "nineteen"];
const EN_TENS = ["", "", "twenty", "thirty", "forty", "fifty", "sixty", "seventy", "eighty", "ninety"];
const SV = ["noll", "ett", "två", "tre", "fyra", "fem", "sex", "sju", "åtta", "nio", "tio", "elva", "tolv", "tretton", "fjorton", "femton", "sexton", "sjutton", "arton", "nitton"];
const SV_TENS = ["", "", "tjugo", "trettio", "fyrtio", "femtio", "sextio", "sjuttio", "åttio", "nittio"];
const NO = ["null", "en", "to", "tre", "fire", "fem", "seks", "sju", "åtte", "ni", "ti", "elleve", "tolv", "tretten", "fjorten", "femten", "seksten", "sytten", "atten", "nitten"];
const NO_TENS = ["", "", "tjue", "tretti", "førti", "femti", "seksti", "sytti", "åtti", "nitti"];
const FR = ["zéro", "un", "deux", "trois", "quatre", "cinq", "six", "sept", "huit", "neuf", "dix", "onze", "douze", "treize", "quatorze", "quinze", "seize", "dix-sept", "dix-huit", "dix-neuf"];
const DE = ["null", "eins", "zwei", "drei", "vier", "fünf", "sechs", "sieben", "acht", "neun", "zehn", "elf", "zwölf", "dreizehn", "vierzehn", "fünfzehn", "sechzehn", "siebzehn", "achtzehn", "neunzehn"];
const DE_TENS = ["", "", "zwanzig", "dreißig", "vierzig", "fünfzig", "sechzig", "siebzig", "achtzig", "neunzig"];

/** Small counts as words (0–99); larger numbers as digits (TTS reads them fine). */
export function spokenNumber(n: number, lang: Lang | string = "en"): string {
	const l = normLang(typeof lang === "string" ? lang : "en");
	if (!Number.isInteger(n) || n < 0 || n >= 100) return String(n);
	const tens = Math.floor(n / 10);
	const ones = n % 10;
	switch (l) {
		case "sv":
			return n < 20 ? SV[n] : ones ? `${SV_TENS[tens]}${SV[ones]}` : SV_TENS[tens];
		case "no":
			return n < 20 ? NO[n] : ones ? `${NO_TENS[tens]}${NO[ones]}` : NO_TENS[tens];
		case "de":
			if (n < 20) return DE[n];
			if (!ones) return DE_TENS[tens];
			return `${ones === 1 ? "ein" : DE[ones]}und${DE_TENS[tens]}`;
		case "fr": {
			if (n < 20) return FR[n];
			const fTens = ["", "", "vingt", "trente", "quarante", "cinquante", "soixante", "soixante", "quatre-vingt", "quatre-vingt"];
			if (tens === 7 || tens === 9) {
				const rest = n - (tens === 7 ? 60 : 80);
				return `${fTens[tens]}${rest === 11 && tens === 7 ? " et " : "-"}${FR[rest]}`;
			}
			if (!ones) return tens === 8 ? "quatre-vingts" : fTens[tens];
			return ones === 1 && tens < 8 ? `${fTens[tens]} et un` : `${fTens[tens]}-${FR[ones]}`;
		}
		default:
			return n < 20 ? EN[n] : ones ? `${EN_TENS[tens]}-${EN[ones]}` : EN_TENS[tens];
	}
}

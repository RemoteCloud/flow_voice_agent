export function t(lang: Lang | string | undefined, key: string, params: Params = {}): string {
	const l = normLang(typeof lang === "string" ? lang : "en");
	let s = T[l][key] ?? T.en[key] ?? key;
	for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
	return s;
}


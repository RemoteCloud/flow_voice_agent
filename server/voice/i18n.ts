/**
 * Everything the hub *says*, in the five supported languages: English, Swedish, Norwegian
 * (bokmål), French and German. The run's language (station / profile / prompt) selects the table;
 * the endpoint's TTS locale follows it. What the hub *understands* is in interpret.ts, which
 * accepts all five vocabularies at once (crews mix languages; the STT locale is a hint).
 */

export type Lang = "en" | "sv" | "no" | "fr" | "de";
export const LANGS: Lang[] = ["en", "sv", "no", "fr", "de"];

/** "nb-NO" → "no", "sv-SE" → "sv", unknown → "en". */
export function normLang(v: string | undefined): Lang {
	const p = (v ?? "en").toLowerCase().slice(0, 2);
	if (p === "nb" || p === "nn" || p === "no") return "no";
	if (p === "sv" || p === "se") return "sv";
	if (p === "fr") return "fr";
	if (p === "de") return "de";
	return "en";
}

/** BCP-47 tag for TTS / STT engines. */
export function localeTag(lang: Lang): string {
	return { en: "en-GB", sv: "sv-SE", no: "nb-NO", fr: "fr-FR", de: "de-DE" }[lang];
}

